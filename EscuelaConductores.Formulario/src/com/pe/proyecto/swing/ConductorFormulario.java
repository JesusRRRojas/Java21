    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
       
        String CodDep = txtCodDep.getText().trim();
        String CodPro = txtCodPro.getText().trim();
        String CodDis = txtCodDis.getText().trim();
        String NroRuc = txtNroRuc.getText().trim();
        String Nombre = txtNombre.getText().trim();
        String Direccion = txtDireccion.getText().trim();
        String Correo = txtCorreo.getText().trim();
        String Telefono = txtTelefono.getText().trim();
        String Estado = txtEstado.getText().trim();
        
        if(CodDep.isEmpty() || CodPro.isEmpty() || CodDis.isEmpty() || NroRuc.isEmpty() || Nombre.isEmpty() || Direccion.isEmpty() || Correo.isEmpty() || Telefono.isEmpty() || Estado.isEmpty() )      
        {
            JOptionPane.showMessageDialog(null,"Debe de ingresar todos los campos");
        }
        else{
            EscuelaConductorDAO conductorDAO = new ConductorDAOImpl();
            Response oValidaciones = new Response();
            EscuelaConductor obj = new EscuelaConductor();

            if(TipoFormulario == 2) obj.setId(getIdConductorAux());
            obj.setCodDep(CodDep);
            obj.setCodPro(CodPro);
            obj.setCodDis(CodDis);
            obj.setNroRuc(NroRuc);
            obj.setNombreEstablecimiento(Nombre);
            obj.setDireccion(Direccion);
            obj.setCorreo(Correo);
            obj.setTelefono(Telefono);
            obj.setEstado(Estado);

            try {
                oValidaciones = conductorDAO.Validaciones(obj);
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(null,"Error : " + ex.getMessage());
                Logger.getLogger(ConductorFormulario.class.getName()).log(Level.SEVERE, null, ex);
            }

            if(oValidaciones.getResultadoBit())
                try {
                        if(TipoFormulario == 1)
                            conductorDAO.insertar(obj);
                        if(TipoFormulario == 2)
                            conductorDAO.actualizar(obj);
                        
                    ConductorBandeja Bandeja = new ConductorBandeja();
                    if(conductorBandeja != null)
                        conductorBandeja.ListarConductores();
                       
                    this.dispose();
                } catch (Exception ex) {
                    JOptionPane.showMessageDialog(null,"Error : " + ex.getMessage());
                    Logger.getLogger(ConductorFormulario.class.getName()).log(Level.SEVERE, null, ex);
                }
            else
                JOptionPane.showMessageDialog(null,"Error : " + oValidaciones.getResultadoDesc());        

           
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed

