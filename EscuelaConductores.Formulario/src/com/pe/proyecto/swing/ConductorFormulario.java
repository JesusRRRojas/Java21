    public void cargarEditar(EscuelaConductor obj){
        System.out.print(obj.toString());
        setIdConductorAux(obj.getId());
        
        EscuelaConductor escuela = ObtenerEscuelaPorId(obj.getId());
        
        
        txtCodDep.setText(escuela.getCodDep());
        txtCodPro.setText(escuela.getCodPro());
        txtCodDis.setText(escuela.getCodDis());
        txtNroRuc.setText(escuela.getNroRuc());
        txtNombre.setText(escuela.getNombreEstablecimiento());
        txtDireccion.setText(escuela.getDireccion());
        txtCorreo.setText(escuela.getCorreo());
        txtTelefono.setText(escuela.getTelefono());
        txtEstado.setText(escuela.getEstado());
        
        obtenerDepartamentos();
        
    }
    private void obtenerDepartamentos()
    {
        
        List<Departamento> departamentos = null;
        try{
            DepartamentoDAO depDAO = new DepartamentoDAOImpl();
            departamentos = depDAO.listarTodos();
      
            // Limpiar el JComboBox antes de agregar nuevos elementos
            cbDepartamentos.removeAllItems();

            // Agregar los departamentos al JComboBox
            for (Departamento dep : departamentos) {
                cbDepartamentos.addItem(dep.getNombreDepartamento());
            }
            
        } catch (Exception e) {
            JPanel.Error(e.getMessage());
        }            
    }
    private EscuelaConductor ObtenerEscuelaPorId(int id){
        EscuelaConductor escuela = new EscuelaConductor();
        try{
            EscuelaConductorDAO conductorDAO = new ConductorDAOImpl();
            escuela = conductorDAO.BuscarPorId(id);
      
        } catch (Exception e) {
            JPanel.Error(e.getMessage());
        }    
        return escuela;
    }
    
